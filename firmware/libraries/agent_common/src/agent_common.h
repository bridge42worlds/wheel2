// agent_common — общий код всех прошивок агентов.
//   светодиод и азбука Морзе (каждое переключение печатается в Serial как "T <millis> <0|1>");
//   идентификация: заводской MAC и номер устройства из реестра registry/devices.csv;
//   заставка при старте: маркер, MAC, маркер, номер, маркер конца.
#pragma once
#include <Arduino.h>

namespace agent {

// ---------- USB-порт ----------
// Serial.begin + безопасный таймаут печати. Таймаут 0 НЕЛЬЗЯ: в ядре 3.3.7
// (HWCDC.cpp) счётчик попыток tries = tx_timeout_ms уходит в переполнение
// (0 - 1 = 4294967295), и печать при воткнутом, но не читаемом порте висит
// ~50 суток. Таймаут 1 мс тоже плох: короткая задержка опроса со стороны
// компьютера уже считается «никто не читает», и начало залпа строк теряется.
// Таймаут 50 мс: если порт не читают, печать один раз ждёт 50 мс, затем идёт
// без ожидания; если читают — короткие задержки компьютера ничего не ломают.
void serial_begin(uint32_t baud = 115200);

// ---------- идентификация ----------
void        identity_init();     // прочитать MAC, найти номер в реестре
const char* mac_str();           // "68:ee:8f:51:a0:18"
const uint8_t* mac_bytes();      // те же 6 байт
const char* mac_tail4();         // последние четыре знака: "a018"
int         device_id();         // номер из реестра; 0 — плата не зарегистрирована
const char* device_label();      // метка из реестра
bool        device_mac(int id, uint8_t mac[6]);   // MAC платы по её номеру в реестре

// ---------- сеть ----------
const char* wifi_ssid();         // из secrets/wifi.ini, вшивается при сборке
const char* wifi_pass();         // пустая строка — пароль не задан
const char* wifi_ssid2();        // запасная сеть (ssid2 в wifi.ini): на неё плата уходит, если основная не пускает; пусто — нет
const char* wifi_pass2();
const char* server_host();       // адрес сервера из wifi.ini; пусто — искать по маяку
const char* ota_key();           // ключ подписи команд OTA из secrets/ota.key (64 знака hex); пусто — OTA закрыта

// ---------- светодиод и Морзе ----------
struct Timing {
  uint32_t unit_ms   = 250;  // единица Морзе
  uint32_t burst_on  = 100;  // вспышка маркера
  uint32_t burst_off = 100;  // пауза быстрого маркера
  uint32_t slow_off  = 400;  // пауза медленного маркера (конец заставки)
};

void led_init(uint8_t pin = LED_BUILTIN, uint8_t on_level = LOW);   // XIAO ESP32-S3: горит при LOW
void led_set(bool on);
void led_quiet(bool on);         // то же без строки "T" в логе — для частого мигания
void burst(int n, uint32_t on_ms, uint32_t off_ms);
void morse_text(const char* s, uint32_t unit_ms);   // без паузы после последней буквы
void gap(uint32_t units, uint32_t unit_ms);

// ---------- температура кристалла ----------
// Датчик настроен на 20–100 °C. temperatureRead() из Arduino настраивает его на
// 10–50 °C, а кристалл под нагрузкой греется до ~60 °C — вне диапазона точность хуже.
// Вместе с temperatureRead() не использовать: датчик в чипе один.
float chip_temp();

// ---------- ядра ----------
// Загрузка каждого ядра в процентах с прошлого вызова: 100 − доля задачи простоя.
struct CoreLoad { float busy0, busy1; };
CoreLoad core_load();
// Таблица задач в Serial: имя, состояние, приоритет, запас стека, ядро;
// затем доля процессорного времени каждой задачи с момента старта.
void task_report();

// ---------- заставка при старте ----------
// 5 быстрых вспышек, 4 знака MAC, 5 быстрых, номер устройства, 5 медленных.
void boot_signature(const Timing& t = Timing());

}  // namespace agent
