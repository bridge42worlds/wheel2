// Аккумуляторы контура: INA219 в плюсе между выключателем и DC-DC (docs/wiring.md, «Аккумуляторы»).
// Ищутся при старте на I2C (D4 — SDA, D5 — SCL), потом на второй шине (D8 — SDA, D9 — SCL), адреса 0x40–0x4F,
// до двух; нет — ничего не происходит. Агент катушки (роль M) читает свой контур (D4/D5, 0x40) и шину колеса —
// на своих выводах D8/D9 (0x40, "w":1) или на тех же D4/D5 с перемычкой A0 (0x41); шину может читать и агент
// на шине (у №6 на тех же D4/D5 — ICM-42688). Второй — в пакете "bat2".
// Раз в секунду: напряжение пары, ток, мА·ч с включения агента — в основной пакет ("bat"). Заряд, сколько
// осталось и тревогу считает сервер (server/battery.py).
#pragma once
#include <Arduino.h>
#include "jsonout.h"

namespace bat {

void begin(bool start_wire);  // start_wire — запустить шину I2C самому (у агента моторов и катушки датчиков обода нет)
bool present();
void add_tel(Out& o);         // ,"bat":{"v":7.912,"i":1234.5,"q":12.34,"n":…,"a":64,"err":0}[,"bat2":{… "a":64,"w":1}]

}  // namespace bat
