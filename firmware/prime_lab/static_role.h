// Роль S — статический акселерометр. Агент только меряет и шлёт оси: ничего
// не генерирует, в группах не участвует, по ESP-NOW не говорит, CSI не пингует.
// Спектр, эталон шума и тревоги считает сервер (server/static_watch.py).
//
// ICM-42688: только ускорение, 1000 Гц, малый шум, FIFO — ни один отсчёт не
// теряется, даже если задача задержалась (FIFO держит 256 отсчётов, забираем
// каждые 10 мс). Среднее по avg отсчётам — на сервер идёт 1000/avg Гц; фильтр
// датчика (3-го порядка) — ниже половины этой частоты, чтобы спектр не
// заворачивался. Измеряет ядро 1 — больше на нём ничего нет.
//
// Отсчёты копятся в кольце и уходят пакетами "acc" по PER_PACKET. В молчании
// копятся (кольца хватает на ~25 с при 500 Гц); переполнилось — старые
// затираются, сервер видит пропуск по номерам отсчётов. I2C: D4 — SDA, D5 — SCL.
#pragma once
#include <Arduino.h>
#include "jsonout.h"

namespace sacc {

static const int PER_PACKET = 140;   // отсчётов в пакете: 840 байт, в base64 — 1120 знаков

bool     begin(uint8_t afs, uint8_t avg);   // найти датчик и запустить измерение на ядре 1
void     set(uint8_t afs, uint8_t avg);     // на ходу: другой предел или усреднение
bool     present();                         // датчик найден и настроен
uint32_t pending();                         // отсчётов ждут отправки
void     add_tel(Out& o);                   // поля для пакета tel: датчик, режимы из регистров, счётчики
// Тело пакета "acc" (после заголовка): номер первого отсчёта, сколько, частота,
// метка времени и сами отсчёты (int16 x y z подряд, base64). Возвращает, сколько
// отсчётов вложено (0 — нечего); отправилось — commit(n).
int      build_acc(Out& o);
void     commit(int n);

}  // namespace sacc
