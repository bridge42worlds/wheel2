// Совместный режим («сообща»): агенты группы делают одно число на всех.
//
// Цикл (подробно — docs/group_protocol.md):
//  1. Число цикла приходит вместе с итогом прошлого цикла (NXT): прошлый мастер
//     берёт его из запаса уцелевших кандидатов. Все сразу проверяют его своими
//     базами Миллера — Рабина (поделены по кругу) и отвечают новому мастеру (RES).
//  2. Итог (NXT). Нашёл свидетеля кто-то — число составное, следующий мастер —
//     нашедший (нашли несколько — выбор по зерну из самого числа). Не нашёл
//     никто — число простое, эстафета следующему по порядку. В том же сообщении —
//     число следующего цикла, а новому мастеру — и остаток запаса.
//  3. Запас. Кончился — новый мастер собирает его, пока все проверяют число:
//     каждый агент сразу шлёт ему K кусочков шума, набранных заранее (PCS),
//     мастер складывает из них K кандидатов в случайном порядке, отсеивает
//     делителями и кладёт уцелевших в запас.
//  4. Запаса нет совсем (начало, сбой) — мастер собирает по запросу (REQ),
//     отсеивает и рассылает число (NUM). Тем же NUM он переспрашивает того,
//     кто не ответил.
//
// Варианты группы (настройка gv):
//  0 — всё выше: одно число на всех, базы поделены по кругу.
//  1 — эстафета: число по-прежнему из кусочков всех, но проверяет один — всеми
//      базами, без кругов ответов. Нашёл простое — ход (TURN) и остаток запаса
//      следующему по порядку, тот сверяет это простое одной другой базой.
//  2 — каскад: то же, но ход у всех сразу — каждый проверяет свои числа из
//      кусочков всех, найденное простое уходит на сверку следующему.
//  В обоих кусочки просят одним широковещательным кадром; ждать их не дольше
//  pw мс (pw > 0) — потом недостающие заменяются своим шумом. Два ядра (dc):
//  шум кусочков набирает производитель на ядре связи, там же отсев, ядро счёта
//  только проверяет.
//
// Протокол живёт в своей задаче на ядре связи; считает ядро 1 по заданиям.
#pragma once
#include <Arduino.h>
#include "config.h"

namespace group {

// ---------- задания ядру счёта ----------
// RTEST — эстафета и каскад: кандидаты подряд в job_data(), всеми базами, до первого
// простого; AUDIT — сверка чужого простого одной базой.
enum JobType : uint8_t { JOB_PIECES = 1, JOB_SIEVE = 2, JOB_TEST = 3, JOB_RTEST = 4, JOB_AUDIT = 5, JOB_TYPES = 6 };

struct Job {
  uint8_t  type;
  uint32_t gs;              // номер настройки: результат прошлой настройки не нужен
  uint32_t cycle;
  uint8_t  round;           // круг сбора внутри цикла
  uint16_t nbytes;          // PIECES: байт шума; SIEVE, TEST, RTEST, AUDIT: длина числа в байтах
  uint8_t  count;           // SIEVE, RTEST: кандидатов подряд в job_data()
  uint8_t  nidx;            // TEST, RTEST, AUDIT: баз
  uint8_t  idx[MAX_BASES];  //   их номера в BASES
};

struct JobResult {
  uint8_t  type;
  uint32_t gs;
  uint32_t cycle;
  uint8_t  round;
  bool     ok;              // false — прервано новыми настройками
  int16_t  value;           // SIEVE: сколько уцелело (они сдвинуты в начало job_data());
                            // TEST, AUDIT: база-свидетель, -1 — нет, -2 — ошибка;
                            // RTEST: номер простого среди кандидатов, -1 — простых нет, -2 — ошибка
  uint8_t  tests;           // TEST: проверено баз; RTEST: проверено кандидатов
  uint32_t us;              // время работы ядра 1
};

uint8_t* job_data();                          // общий буфер задания (одно задание за раз)
bool take_job(Job& j, TickType_t wait);       // ядро 1
void job_done(const JobResult& r);            // ядро 1

// ---------- управление ----------
void begin();                                 // после Wi-Fi: ESP-NOW, очереди, задача
void configure(const GenConfig& c);           // ядро 0, при новых настройках
void rest(uint16_t secs);                     // ядро 0: отдых по очереди на secs секунд, 0 — назад (эстафета, каскад)
// Простое, найденное в режиме «каждый сам» (ядро 1): объявить сету B одним
// широковещательным кадром. Не ждёт: очередь занята — не объявляется (ann_drop).
void announce_prime(const uint8_t* num, uint16_t nbytes);
// Два ядра в эстафете и каскаде: шум кусочков набирает производитель (prime_lab.ino,
// ядро связи, низший приоритет). prod_len — сколько байт в одном наборе кусочков
// (0 — набирать не нужно) и номер настройки; prod_put — отдать набор, ждёт места в
// очереди, пока не abort.
int  prod_len(uint32_t* gs);
bool prod_put(const uint8_t* b, int len, uint32_t gs, volatile bool* abort);

// ---------- статистика (накопительно с момента применения настроек) ----------
// Эстафета и каскад пишут в те же поля: цикл — ход (до rk простых), мастер — проверяющий;
// t: простой ядра счёта без чисел, прочий его счёт (шум, отсев), проверка, передача хода,
// весь ход; согласие — сверка чужих простых одной другой базой.
struct Stats {
  uint8_t  active = 0;          // агент в группе
  uint8_t  gv = 0;              // вариант группы (config.h)
  uint8_t  role = 0;            // 0 — нет, 1 — участник, 2 — мастер (проверяющий)
  uint8_t  master = 0;          // номер текущего мастера
  uint8_t  phase = 0;
  uint32_t cycle = 0;
  uint32_t cycles = 0;          // циклов, итог которых агент видел
  uint32_t cycles_m = 0;        // из них агент был мастером
  uint32_t primes_m = 0;        // простых, найденных в циклах этого мастера
  uint32_t regathers = 0;       // сборов, после которых не уцелел ни один кандидат
  uint32_t gathers = 0;         // мастер: кругов сбора
  uint32_t cands = 0, survivors = 0;  // мастер: кандидатов отсеяно / уцелело
  uint32_t rsv_drop = 0;        // уцелевших, не влезших в запас
  uint32_t starts = 0;          // мастер: циклов, начатых без числа (сбор по запросу)
  uint32_t fill_waits = 0;      // мастер: ответы есть, а числа на следующий цикл ещё нет
  uint32_t pre_hit = 0, pre_miss = 0;  // просьб о кусочках: заготовка была готова / набирали
  uint32_t early = 0;           // ответов и кусочков, пришедших раньше итога прошлого цикла
  uint32_t hop_us = 0;          // передача эстафеты: сколько идёт итог до нового мастера, мкс
  uint32_t asks_tx = 0, asks_rx = 0;              // переспросов отправлено / получено
  uint32_t brk_pcs = 0, brk_res = 0, brk_hand = 0;  // разрывов: нет кусочков, нет ответа, нет подтверждения эстафеты
  uint32_t resyncs = 0;         // агент долго не слышал мастера и начал цикл сам
  uint32_t conflicts = 0;       // два мастера сразу: уступил тому, у кого цикл больше
  uint32_t stale = 0;           // сообщений из прошлых циклов
  uint32_t streak = 0, streak_max = 0;            // циклов подряд без переспросов и разрывов
  uint32_t streak_ms = 0, streak_ms_max = 0;      // их длительность
  uint64_t clean_ms = 0;        // всего времени в чистых сериях
  uint64_t t_gather = 0, t_sieve = 0, t_test = 0, t_hand = 0, t_cycle = 0;  // мастер: мкс по этапам
  uint64_t c_pieces = 0, c_sieve = 0, c_test = 0;  // из них чистый счёт (самый долгий из агентов), мкс
  uint32_t tx = 0, rx = 0, tx_fail = 0;
  uint32_t tx_cb = 0;           // отчётов радио об отправке
  uint32_t tx_drop = 0;         // очередь отправки полна — кадр выброшен
  uint32_t tx_err = 0;          // радио не приняло кадр к отправке (esp_now_send — ошибка)
  uint32_t txq_max = 0;         // наибольшая длина очереди отправки
  uint32_t tx_stuck = 0;        // отчёта радио не было 50 мс
  uint32_t job_lost = 0;        // итогов заданий ядра 1 потеряно (очередь событий была полна) или не дождались 5 с
  uint32_t ok_to[MAX_GROUP] = {};    // по участникам (место в группе): доставлено адресно
  uint32_t fail_to[MAX_GROUP] = {};  //   не доставлено (радио не получило подтверждения)
  int8_t   rssi_from[MAX_GROUP] = {}; //   с каким сигналом слышим этого участника, дБм
  uint32_t found = 0;           // сколько раз моя база нашла свидетеля (эстафета, каскад: составных отбраковано)
  // ---------- эстафета и каскад ----------
  uint32_t truncs = 0;          // кругов сбора, собранных без чьих-то кусочков (ждали pw мс)
  uint32_t trunc_pcs = 0;       // наборов кусочков, заменённых своим шумом
  uint16_t rr = 0;              // запас уцелевших кандидатов у проверяющего сейчас
  uint32_t mute = 0;            // раз участник замолчал (нет кусочков после трёх просьб, не принял ход) — его не ждём
  uint16_t mute_mask = 0;       // кто молчит сейчас: бит на место в группе
  uint32_t rests = 0;           // отдыхов по очереди
  uint8_t  resting = 0;         // 1 — отдыхает, 2 — уйдёт, как доведёт свой ход
  uint16_t rest_left = 0;       // секунд отдыха осталось
  uint64_t sv_cand = 0, sv_tdr = 0, sv_tdcyc = 0;   // отсев на ядре связи (два ядра): кандидатов, отсеяно, такты
  // ---------- согласие агентов: одно число проверяют все, ответы обязаны сходиться ----------
  // Случайное составное выдаёт свидетеля почти любой базе, поэтому в каждом цикле либо
  // нашли все, либо никто. Нашли не все (split) — либо редчайший псевдопростой к чьим-то
  // базам (сервер перепроверит), либо ошибка счёта или передачи. При all = 1 все агенты
  // проверяют все базы по порядку, и номер первой базы-свидетеля обязан совпасть у всех
  // (disagree — не совпал).
  uint32_t agree = 0;           // мастер: циклов, где ответы всех сравнивались
  uint32_t split = 0;           // мастер: свидетеля нашли не все (0 < нашедших < участников)
  uint32_t disagree = 0;        // мастер, all = 1: первые базы-свидетели у агентов разные
  char     last_split[132] = "";   // число последнего расхождения (hex, до 256 бит) и ответы агентов
  // ---------- рассеяние ----------
  uint8_t  set = 0;             // 0 — агент в сете A (генерация), 1 — в сете B (рассеяние)
  uint32_t ann = 0;             // A: простых объявлено сету B
  uint32_t ann_drop = 0;        // A: не объявлено — очередь занята
  uint32_t heard = 0;           // кадров рассеяния своей настройки, услышанных этим агентом
  uint32_t rx_drop = 0;         // принятых кадров ESP-NOW не влезло в очередь событий — потеряны
  uint32_t prx = 0;             // B: простых получено
  uint32_t stx = 0;             // B: своих кадров рассеяния выпущено
  uint32_t sdrop = 0;           // B: простых пропущено — очередь полна
  uint32_t swait = 0;           // B: простых ждали шум
  uint32_t chs = 0, chf = 0, chd = 0;   // B: эстафет начато / передано дальше / выпущено в эфир
  uint64_t slat = 0;            // B: сумма задержек от получения простого до своего кадра, мкс
  uint32_t sn = 0;              //    сколько их
  uint32_t sbg = 0;             // B: кадров фона выпущено
  uint32_t espnow_ver = 0;
  char     last_prime[132] = "";  // последнее простое группы, найденное в мой цикл (до 512 бит)
};

void snapshot(Stats& s);

// ---------- пульс: соседи, которых слышно (кадр «я жив» раз в секунду от каждого агента) ----------
struct Neighbor {
  uint8_t  id = 0;
  uint8_t  mac[6] = {};
  int8_t   rssi = 0;            // сглаженный сигнал, дБм
  uint32_t n = 0;               // кадров пульса принято
  int64_t  last_us = 0;         // когда слышали последний раз
  uint8_t  run = 0;             // сосед считает
  int8_t   temp = 0;            // его кристалл, °C
};
static const int NB_MAX = 36;
void set_alive_info(float temp, bool run);     // что писать в свой пульс
void set_alive_rate(uint8_t hz);               // кадров пульса в секунду (настройка hb, 1..20)
void radio_pause(bool off);                    // Wi-Fi выключен на шаге: ни пульса, ни кадров; false — после включения
                                               // Wi-Fi: ESP-NOW и адресаты поднимаются заново, если сброшены вместе с ним
int  neighbors(Neighbor* out, int max);        // снимок таблицы соседей

}  // namespace group
