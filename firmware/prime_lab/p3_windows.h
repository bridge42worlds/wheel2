// Фаза 3: окна невесомости по датчикам (docs/phase3.md).
//
// На агенте до двух датчиков ICM-20948, каждый на своём канале I2C: первый — D4 (SDA), D5 (SCL), второй —
// D8 (SDA), D9 (SCL). Окно считается по каждому датчику отдельно: агент сам опрашивает датчик, видит вход в
// зону (ускорение упало ниже порога, который отвечает ширине окна), и снимает записи за окно:
//   fm = 1 — из буфера самого датчика: при входе буфер сбрасывается, агент к датчику не обращается всё окно
//            и забирает буфер одним чтением после него;
//   fm = 0 — прямым чтением, запись за записью.
// После окна читается магнитометр. Снятое окно уходит ядру счёта: каждая запись целиком → SHA-256 → кандидат.
//
// Задача датчиков — на ядре счёта, выше счёта по приоритету: работа короткая, окно не пропускается из-за
// проверки чисел прошлого окна. Радио в окнах пока не выключается — залпы и общее время будут отдельным шагом.
#pragma once
#include <Arduino.h>
#include "config.h"
#include "jsonout.h"

namespace p3 {

static const int NSENS = 2;
static const int MAXREC = 384;        // записей в одном окне: буфер датчика 4 кБ — 341 запись
static const int RECLEN = 18;         // запись в хеш: ax ay az gx gy gz mx my mz, int16 младшим байтом вперёд

struct Window {                       // снятое окно
  uint8_t  sensor;                    // 0, 1
  uint8_t  fm;                        // как читали
  uint16_t n;                         // записей
  uint32_t seq;                       // номер окна этого датчика
  int64_t  t_enter_us;                // вход в зону, часы платы
  uint32_t dur_us;                    // сколько длилось окно
  float    w;                         // скорость вращения на входе, рад/с
  float    a_enter;                   // ускорение на входе, g
  float    a_min;                     // наименьшее ускорение в окне, g
  int16_t  mag[3];                    // поле сразу после окна, сырые отсчёты
  bool     has_mag;
  int16_t  rec[MAXREC][6];            // ax ay az gx gy gz
};

struct Find {                         // найденное простое — строка таблицы находок
  uint8_t  num[32];
  uint8_t  sensor;
  uint16_t idx;                       // номер записи в окне
  uint32_t seq;                       // номер окна датчика
  int64_t  t_us;                      // момент записи (вход в окно + номер записи / частота), часы платы
};
static const int NFIND = 64;          // таблица находок: последние NFIND

// После rim::begin() и bat::begin(): найти датчики, измерить их буфер, запустить задачу. bus1_taken — на D4/D5 уже
// работает датчик обода прежнего типа (ICM-42688): первую шину не трогаем.
void    begin(bool bus1_taken);
uint8_t present();                    // бит на датчик
void    configure(const GenConfig& c);   // p3, run, win, wo, fm — на ходу

// ---- ядро счёта ----
bool take(Window*& w, TickType_t wait);    // забрать снятое окно; после обработки — release
void release(Window* w);
void record(const Window& w, int i, uint8_t out[RECLEN]);   // запись i окна — как она идёт в хеш
void found(const Window& w, int i, const uint8_t* num);     // простое — в таблицу находок
void done(const Window& w, uint32_t cands, uint32_t primes, uint32_t us);   // итог окна — в счётчики

// ---- телеметрия ----
void add_tel(Out& o);                 // тело пакета "p3"
int  finds(Find* out, int max);       // снимок таблицы находок (для залпа)

}  // namespace p3
