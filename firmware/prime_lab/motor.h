// Роль M — агент моторов. Стоит на неподвижной раме (колёса крутятся — к ним провод не протянуть) и
// крутит два щёточных мотора 12 В (36GP-555, редуктор 112 об/мин) через H-мосты DRV8871: мотор колеса 1 —
// D0 (IN1), D1 (IN2); колеса 2 — D2, D3. Питание моторов — блок 12 В, агента — через понижающий DC-DC 5 В.
//
// ШИМ 20 кГц (не слышно), «медленный спад»: один вход моста всё время 1, на другом ШИМ — в паузах мост
// не отпускает мотор, а подтормаживает (оба входа 1): обороты ровнее и держатся на малом ходу.
// Разгон и торможение — плавно (ramp ‰ ШИМ в секунду). Направление меняется только через остановку
// и паузу 1 с: реверс на ходу — удар по редуктору и бросок тока. Сторож: нет команды MOT дольше wd
// секунд — моторы плавно встают (сервер шлёт команду раз в секунду, пока что-то крутится).
#pragma once
#include <Arduino.h>
#include "jsonout.h"

namespace motor {

void begin();
// MOT a=… b=… r=… w=…: a, b — ШИМ колеса 1 и 2 в ‰ со знаком направления (−1000…1000, 0 — встать),
// r — разгон ‰ в секунду (50…5000), w — сторож, с (0 — выкл, до 60). Пропущенное — как было.
void command(const char* args);
void stop();                  // плавно встать (то же, что a=0 b=0)
void add_tel(Out& o);         // поля для tel: цель, ШИМ сейчас, состояние, разгон, сторож

}  // namespace motor
