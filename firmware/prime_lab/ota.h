// Прошивка по Wi-Fi (OTA) с подписью и откатом.
//
// Сервер командой "OTA url=… md5=… len=… ver=… t=… sig=…" (UDP 5007, только со
// своего адреса) велит агенту скачать образ по HTTP и записать его в свободный
// раздел (app0/app1 — у платы два раздела по 3,3 МБ). Команда подписана: sig —
// HMAC-SHA256 ключом из secrets/ota.key (вшит при сборке, в git не попадает) от
// строки "url|md5|len|ver|t". Без ключа чужой компьютер в сети прошивку не подменит;
// t растёт от команды к команде (хранится в памяти платы) — старую команду не
// повторить. Образ проверяется по длине и MD5; записан — перезапуск.
//
// Новая прошивка стартует «на пробу»: загрузчик держит её в состоянии «ждёт
// подтверждения». Подтверждаем, когда агент минуту на связи с сервером (Wi-Fi есть,
// маяк сервера услышан). Не вышел на связь за 10 минут — откатываемся сами;
// перезапустился раньше подтверждения (сбой, вылет) — откатит загрузчик. Так плата,
// которую нельзя достать, не остаётся с нерабочей прошивкой.
#pragma once
#include <Arduino.h>

namespace ota {

// Начать загрузку. nullptr — пошло; иначе причина отказа: нет Wi-Fi, уже идёт,
// эта прошивка сама ещё не подтверждена, плохая подпись, старая команда, плохие параметры.
const char* start(const char* url, const char* md5, uint32_t len, const char* ver, uint32_t t, const char* sig);
int         state();            // 0 — нет, 1 — загрузка, 2 — записано, перезапуск, -1 — ошибка
const char* err();              // текст ошибки при state() == -1
uint32_t    progress();         // байт загружено
bool        pending_verify();   // эта прошивка ещё не подтверждена
const char* slot();             // раздел, из которого работаем: app0 или app1
// Раз в секунду: healthy — агент на связи с сервером. Подтверждает новую прошивку
// через CONFIRM_S секунд на связи; не на связи дольше ROLLBACK_S — откат.
void        tick(bool healthy, uint32_t uptime_ms);

static const uint32_t CONFIRM_S  = 60;
static const uint32_t ROLLBACK_S = 600;

}  // namespace ota
