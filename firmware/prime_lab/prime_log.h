// Журнал простых: каждое найденное простое — с меткой времени агента — уходит на
// сервер пакетами "prm" (настройка pl = 1). Простое кладёт ядро счёта (каждый сам)
// или задача группы (мастер, сообща); забирает задача связи. Кольцо 16 КБ — около
// 15 с при 25 простых/с по 256 бит; переполнилось (молчание телеметрии, нет связи) —
// простое не записывается и считается потерянным (pll в телеметрии).
//
// Зачем: сервер перепроверяет каждое простое (а не одно в секунду), хранит поток
// простых с временем — по нему можно сверять моменты находок с показаниями датчиков
// и проверять статистику самого потока (остатки, биты, промежутки).
#pragma once
#include <Arduino.h>
#include "jsonout.h"

namespace plog {

void     configure(bool on, uint32_t cid);        // при новых настройках: включить/выключить; новый номер — счёт заново
void     push(const uint8_t* num, uint16_t nbytes, uint8_t src);   // src: 0 — каждый сам, 1 — сообща (мастер)
uint32_t pending();                               // записей ждут отправки
uint32_t total();                                 // простых записано с начала настройки (включая потерянные)
uint32_t lost();                                  // не влезло в кольцо
// Записать в пакет сколько влезет: [ms,"HEX",src],… — через запятую, без скобок списка.
// Возвращает число записей; после отправки — commit(n).
int      build(Out& o);
void     commit(int n);

}  // namespace plog
