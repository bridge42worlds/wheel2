//                gm=68ee8f51a018,68ee8f51ae20 nr=1 k=24 pre=1 cpu=240 txp=20 ping=100 led=1 tp=1000
//                role=0 sm=1 sf=0 cf=0 sh=0 bgr=0 ss=0 bg=3 bm=68ee8f51a03c ba=1,2 afs=2 avg=2 pl=0 dur=0 ro=0
//                raw=0 xf=4 det=0 p3=0 win=30 wo=0 fm=1 vl=0 vm=0 vn=5 vj=40 vr=1 vs=80 vc=0".
// Незаданные поля берутся из cur. При ошибке — false и причина в err.
bool parse_config(const char* line, const GenConfig& cur, GenConfig& out, char* err, size_t errlen);

// Маска шума для entropy_fill: источники (биты 0–7), как брать шум (8–10), во сколько сжимать сырьё (12–16) и
// слов регистра ГСЧ на бит SHA-256 (17–19).
// 08.11: источник шума по команде NS — без нового номера настройки и без сброса счёта (−1 — как в настройке);
// сбрасывается новой настройкой. Нужен, чтобы все платы меняли источник одновременно и в тишине.
extern volatile int16_t g_ns_override;
inline uint32_t noise_mask(const GenConfig& c) {
  const uint32_t src = g_ns_override >= 0 ? (uint32_t)g_ns_override : (uint32_t)c.src;
  return src | (uint32_t)c.raw << 8 | (uint32_t)c.xf << 12 | (uint32_t)c.rw << 17;
}
